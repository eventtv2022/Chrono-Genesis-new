def make_lines(d: dict) -> str:
    parts = []
    for k, v in d.items():
        escaped = v.replace("\\", "\\\\").replace('"', '\\"')
        # Restore intentional \\n as literal \n in the TS string
        escaped = escaped.replace("\\\\n", "\\n")
        parts.append(f'    {k}: "{escaped}"')
    return ",\n".join(parts) + ","

errors = []
for lang, translations in LANGS.items():
    new_lines = make_lines(translations)
    # Find the end of this language block: last key before closing },
    pattern = rf'(  {re.escape(lang)}: {{.*?file_limit_both: "[^"]*",)\s*\n  }},'
    replacement = rf'\1\n{new_lines}\n  }},'
    new_content = re.sub(pattern, replacement, content, count=1, flags=re.DOTALL)
    if new_content == content:
        errors.append(f"WARNING: no match for lang={lang}")
    content = new_content

for e in errors:
    print(e, file=sys.stderr)

with open(FILE, "w", encoding="utf-8") as f:
    f.write(content)

print(f"Done. {len(LANGS)} languages patched.")
