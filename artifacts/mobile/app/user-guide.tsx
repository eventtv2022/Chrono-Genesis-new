const lines = guideMarkdown.split("\n");

export default function UserGuideScreen() {
  const colors = useColors();
  const { lang } = useLanguage();
  const router = useRouter();
  const insets = useSafeAreaInsets();
  const isRu = lang === "ru";

  return (
    <View style={[styles.screen, { backgroundColor: colors.background }]}>
      <View style={[styles.header, { paddingTop: Math.max(insets.top, 16) + 8, borderBottomColor: colors.border }]}>
        <TouchableOpacity onPress={() => router.back()} accessibilityRole="button" accessibilityLabel={isRu ? "Назад" : "Back"} style={styles.back}>
          <Feather name="arrow-left" size={20} color={colors.foreground} />
        </TouchableOpacity>
        <View style={{ flex: 1 }}>
          <Text style={[styles.eyebrow, { color: colors.primary }]}>{isRu ? "TIMENATION" : "TIMENATION"}</Text>
          <Text style={[styles.title, { color: colors.foreground }]}>{isRu ? "Руководство пользователя" : "User guide"}</Text>
        </View>
        <Feather name="book-open" size={19} color={colors.primary} />
      </View>
      {!isRu && <Text style={[styles.languageNote, { color: colors.mutedForeground }]}>Полная версия руководства пока доступна на русском языке.</Text>}
      <ScrollView contentContainerStyle={[styles.content, { paddingBottom: insets.bottom + 32 }]}>
        {lines.map((line, index) => {
          const text = line.trim();
          if (!text) return <View key={`space-${index}`} style={styles.spacer} />;
          const heading = /^(#{1,4})\s+(.+)$/.exec(text);
          if (heading) {
            const level = heading[1].length;
            const title = heading[2].replace(/\*\*/g, "");
            return (
              <Text
                key={`heading-${index}`}
                style={[
                  styles.heading,
                  { color: level <= 2 ? colors.primary : colors.foreground },
                  level === 1 ? styles.h1 : level === 2 ? styles.h2 : styles.h3,
                ]}
              >
                {title}
              </Text>
            );
          }
          const bullet = text.startsWith("- ");
          const numbered = /^\d+\.\s/.test(text);
          const body = text.replace(/^(?:-\s|\d+\.\s)/, "").replace(/\*\*/g, "");
          return (
            <Text key={`text-${index}`} style={[styles.paragraph, { color: colors.foreground }, (bullet || numbered) && styles.listItem]}>
              {bullet ? "• " : numbered ? `${text.match(/^\d+/)?.[0]}. ` : ""}{body}
            </Text>
          );
        })}
      </ScrollView>
    </View>
  );
}

